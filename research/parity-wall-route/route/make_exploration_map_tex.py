"""Generate the English exploration map as a TikZ figure for the paper.

Writes ../paper_parity/exploration_map.tex, which is input from ai_workflow.tex.
Keep the data in sync with make_exploration_map.py (Chinese version).
"""

STYLE = {
    'strict':   dict(fill='red!7',    draw='red!70!black',    line='very thick',            tag='theorem'),
    'model':    dict(fill='red!7',    draw='red!70!black',    line='very thick',            tag='thm.\\ in model'),
    'analysis': dict(fill='orange!6', draw='red!60!black',    line='thick, dashed',         tag='analysis'),
    'numeric':  dict(fill='orange!6', draw='red!60!black',    line='thick, densely dotted', tag='numerical'),
    'proved':   dict(fill='green!10', draw='green!50!black',  line='very thick',            tag='proved'),
    'ffonly':   dict(fill='green!5',  draw='green!50!black',  line='thick',                 tag='$\\mathbb F_q[T]$ only'),
    'cond':     dict(fill='yellow!12', draw='yellow!50!black', line='thick',                tag='conditional'),
    'low':      dict(fill='gray!5',   draw='gray!70',         line='thick, dashed',         tag='low priority'),
}

COLUMNS = [
    ('Original programme (audit)', 'green!45!black', [
        ('strict', 'Bridge A (operator)', 'Gate A is the twin residual itself'),
        ('strict', 'Bridge B (dynamical)', 'cylinder criterion contains its conclusion'),
        ('strict', 'Metric certificates', 'same-mass adversary misses the seed'),
        ('proved', 'Conditional route (Thm.~B)', 'GEH + PND$_{\\log}$ $\\Rightarrow$ twin primes'),
        ('proved', 'Coherence (Thm.~C)', 'one parity parameter on rough pairs'),
    ]),
    ('Known parity mechanisms', 'red!55!black', [
        ('strict', 'Dilation + spectral (Thm.~A)', 'reach $z\\le\\exp(O(\\sqrt{\\log x}))$'),
        ('strict', 'Entropy decrement (Thm.~E)', 'reach $z\\le(\\log x)^{O(\\varepsilon^4)}$'),
        ('numeric', 'Amplification step L4', 'rough-graph degree $\\to0$ ($x\\le10^8$)'),
        ('analysis', 'FI bilinear hypothesis (B)', 'parity-complete for twins'),
        ('analysis', 'L\\"u--Wang--Wu mechanism', 'reach $z\\le\\exp((\\log x)^{1/5})$'),
    ]),
    ('Screening for a new symmetry', 'orange!60!black', [
        ('strict', 'Dilation by large primes', 'rough-dilator case of Thm.~A'),
        ('analysis', 'Extracting few large primes', '$\\sqrt x$ barrier, arbitrary weights'),
        ('analysis', 'Gowers norms', 'twins have infinite complexity'),
        ('analysis', 'Automorphic / Kuznetsov', '$\\lambda$ is not automorphic'),
        ('analysis', 'Number-field spin (FI)', 'split algebra $\\mathbb Q\\times\\mathbb Q$: no symbol'),
        ('cond', 'Siegel zeros (Heath-Brown)', 'only if a Siegel zero exists'),
        ('analysis', 'Ergodic / Furstenberg', 'roughness varies with scale'),
        ('analysis', 'Fourier / Chen switching', 'Type I only: parity principle'),
        ('ffonly', 'Pellet formula', '$\\mu=(-1)^{\\deg}\\chi(\\operatorname{disc})$; no $\\mathbb Z$ analogue'),
    ]),
    ('Bold hypotheses (H series)', 'blue!50!black', [
        ('strict', 'H1 Jacobi symbol of $n\'$', '$(n\'/n)=(-1)^{k(k-1)/2}$, blind to $\\omega(n)$'),
        ('analysis', 'H2 another parity detector', 'parity is one-dimensional (Thm.~4.1)'),
        ('numeric', 'H5 low complexity of $\\lambda$', 'sign entropy $\\approx1$ bit per rough site'),
        ('model', 'H3 parity linear program', 'independent extension: $\\delta=0$ feasible'),
        ('numeric', 'H6 base-$p$ Pellet analogue', 'no correlation at $10^8$ ($|z|\\le1.65$)'),
        ('low', 'H7 rough-scale dichotomy', 'second branch is rough Chowla'),
        ('strict', 'H8 $\\ell^p$ certificates', '$\\ell^p$ dominated by $\\ell^2$ (Prop.~\\ref{prop:L})'),
        ('strict', 'H9 derivative lines on $\\mathbb Z$', 'no derivations on $\\mathbb Z$ (Prop.~\\ref{prop:noderiv})'),
    ]),
]

# 2x2 grid: columns 0,1 on the top row, columns 2,3 on the bottom row.
COLW, GAP, BOXH, STEP, HEAD = 7.3, 0.4, 0.95, 1.08, 0.75
W = 2 * COLW + GAP
out = [r'% Exploration map (generated by route/make_exploration_map_tex.py). Included from ai_workflow.tex.',
       r'\begin{figure}[H]', r'\centering', r'\resizebox{\textwidth}{!}{%',
       r'\begin{tikzpicture}[font=\sffamily]']
row1 = max(len(COLUMNS[0][2]), len(COLUMNS[1][2]))
row2 = max(len(COLUMNS[2][2]), len(COLUMNS[3][2]))
tops = [0.0, 0.0, -(row1 * STEP + HEAD + 0.35), -(row1 * STEP + HEAD + 0.35)]
for ci, (title, color, items) in enumerate(COLUMNS):
    x = (ci % 2) * (COLW + GAP)
    y0 = tops[ci]
    out.append(rf'\node[fill={color}, text=white, minimum width={COLW}cm, minimum height=0.62cm, inner xsep=0pt, outer sep=0pt, rounded corners=3pt, font=\small\bfseries\sffamily] at ({x + COLW / 2:.3f},{y0 + 0.45:.3f}) {{{title}}};')
    for k, (st, name, why) in enumerate(items):
        s = STYLE[st]
        y = y0 - k * STEP
        out.append(rf'\draw[{s["line"]}, draw={s["draw"]}, fill={s["fill"]}, rounded corners=3pt] ({x:.3f},{y:.3f}) rectangle ({x + COLW:.3f},{y - BOXH:.3f});')
        out.append(rf'\node[anchor=north west, font=\footnotesize\bfseries\sffamily, inner sep=0pt] at ({x + 0.14:.3f},{y - 0.14:.3f}) {{{name}}};')
        out.append(rf'\node[anchor=north east, font=\scriptsize\bfseries\sffamily, text={s["draw"]}, inner sep=0pt] at ({x + COLW - 0.12:.3f},{y - 0.16:.3f}) {{{s["tag"]}}};')
        out.append(rf'\node[anchor=south west, font=\scriptsize\sffamily, text=black!75, inner sep=0pt] at ({x + 0.14:.3f},{y - BOXH + 0.14:.3f}) {{{why}}};')
yb = tops[2] - row2 * STEP - 0.1
out.append(rf'\draw[thick, draw=yellow!50!black, fill=yellow!10, rounded corners=4pt] (0,{yb:.3f}) rectangle ({W:.3f},{yb - 1.15:.3f});')
out.append(rf'\node[align=center, text width={W - 0.4:.2f}cm, font=\footnotesize\bfseries\sffamily, text=yellow!30!black] at ({W / 2:.3f},{yb - 0.575:.3f}) '
           r'{Common obstruction: known parity-breaking mechanisms use multiplicativity at many small primes, or algebraic structure that $\mathbb Z$ lacks. '
           r'The twin parity parameter lives on $x^\eta$-rough integers with at most $1/\eta$ prime factors, where both resources are absent.};')
yl = yb - 1.5
legend = ['strict', 'model', 'analysis', 'numeric', 'proved', 'ffonly', 'cond', 'low']
for j, kk in enumerate(legend):
    s = STYLE[kk]
    lx = (j % 4) * (W / 4)
    ly = yl - (j // 4) * 0.5
    out.append(rf'\draw[{s["line"]}, draw={s["draw"]}, fill={s["fill"]}, rounded corners=2pt] ({lx:.3f},{ly:.3f}) rectangle ({lx + 0.55:.3f},{ly - 0.3:.3f});')
    out.append(rf'\node[anchor=west, font=\scriptsize\sffamily] at ({lx + 0.68:.3f},{ly - 0.15:.3f}) {{{s["tag"]}}};')
out.append(r'\end{tikzpicture}}')
out.append(r"""\caption{Map of every route explored in this project, with its status. ``Theorem'' means a complete proof in this paper or in the separate audit of the original programme (first column); ``thm.\ in model'' means an explicit construction that is rigorous within the stated model; ``analysis'' and ``numerical'' are judgements about specific arguments or data, not theorems. All entries were obtained with AI assistance and have not yet been checked by a specialist (Appendix~\ref{app:ai}).}""")
out.append(r'\label{fig:exploration}')
out.append(r'\end{figure}')
open('../paper_parity/exploration_map.tex', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('wrote ../paper_parity/exploration_map.tex')
