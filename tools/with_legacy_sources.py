#!/usr/bin/env python3
"""Run a command with validated, offline original Git source objects available.

Git itself resolves and reads the original objects. No Git command is mocked,
no checker is patched, and no scientific result is regenerated by this runner.
"""
from __future__ import annotations

import os
import sys

from legacy_provenance import ROOT, environment, validate_archive


def main() -> None:
    command = sys.argv[1:]
    if command[:1] == ["--"]:
        command = command[1:]
    if not command:
        raise SystemExit("usage: python -B tools/with_legacy_sources.py -- COMMAND [ARG ...]")
    if any(os.environ.get(name) for name in ("GIT_DIR", "GIT_WORK_TREE", "GIT_OBJECT_DIRECTORY", "GIT_INDEX_FILE")):
        raise SystemExit("remove inherited Git repository/object/index overrides before running checks")
    validate_archive()
    os.chdir(ROOT)
    os.execvpe(command[0], command, environment())


if __name__ == "__main__":
    main()
